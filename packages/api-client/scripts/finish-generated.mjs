import { readFile, readdir, writeFile } from 'node:fs/promises';

// orval tags-split leaves two gaps for NodeNext ESM: endpoint files import the "../model"
// directory, and there is no barrel for the endpoint folders.
const root = new URL('../src/generated/', import.meta.url);
const tags = (await readdir(root, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory() && entry.name !== 'model')
  .map(({ name }) => name)
  .sort();
for (const tag of tags) {
  const file = new URL(`${tag}/${tag}.ts`, root);
  const source = await readFile(file, 'utf8');
  await writeFile(
    file,
    source.replaceAll(/from (["'])\.\.\/model\1/g, 'from $1../model/index.js$1'),
  );
}
const exports = ['./model/index.js', ...tags.map((tag) => `./${tag}/${tag}.js`)];
await writeFile(
  new URL('index.ts', root),
  `// Generated by scripts/finish-generated.mjs. Do not edit manually.\n${exports.map((path) => `export * from '${path}';`).join('\n')}\n`,
);
